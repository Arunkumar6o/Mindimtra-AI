interface LanguageContextType {
  currentLanguage: string;
  setLanguage: (code: string) => void;
  isDrawerOpen: boolean;
  setIsDrawerOpen: (open: boolean) => void;
  openLanguageDrawer: () => void;
  closeLanguageDrawer: () => void;
  t: (key: string, defaultText?: string) => string;
  selectedLanguageObj: Language;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [currentLanguage, setCurrentLanguageState] = useState<string>(() => {
    return localStorage.getItem('mindmitra_language') || 'en';
  });
  const [isDrawerOpen, setIsDrawerOpen] = useState<boolean>(false);

  const setLanguage = (code: string) => {
    setCurrentLanguageState(code);
    localStorage.setItem('mindmitra_language', code);
    document.documentElement.lang = code;
  };

  useEffect(() => {
    document.documentElement.lang = currentLanguage;
  }, [currentLanguage]);

  const openLanguageDrawer = () => setIsDrawerOpen(true);
  const closeLanguageDrawer = () => setIsDrawerOpen(false);

  const selectedLanguageObj = LANGUAGES.find((l) => l.code === currentLanguage) || LANGUAGES[0];

  const t = (key: string, defaultText?: string): string => {
    const langDict = TRANSLATIONS[currentLanguage] || TRANSLATIONS['en'];
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    // Fallback to English dictionary if present
    if (TRANSLATIONS['en'] && TRANSLATIONS['en'][key]) {
      return TRANSLATIONS['en'][key];
    }
    return defaultText || key;
  };

  return (
    <LanguageContext.Provider
      value={{
        currentLanguage,
        setLanguage,
        isDrawerOpen,
        setIsDrawerOpen,
        openLanguageDrawer,
        closeLanguageDrawer,
        t,
        selectedLanguageObj
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

const defaultFallbackContext: LanguageContextType = {
  currentLanguage: 'en',
  setLanguage: () => {},
  isDrawerOpen: false,
  setIsDrawerOpen: () => {},
  openLanguageDrawer: () => {},
  closeLanguageDrawer: () => {},
  t: (key: string) => TRANSLATIONS['en']?.[key] || key,
  selectedLanguageObj: LANGUAGES[0]
};

export const useLanguage = (): LanguageContextType => {
  const context = useContext(LanguageContext);
  return context || defaultFallbackContext;
};
